import bcrypt from 'bcryptjs';
import AnimationModel from '../models/animation.model';
import AvatarItemModel from '../models/avatar-item.model';
import ItemModel from '../models/item.model';
import UserModel from '../models/user.model';
import { ANIMATIONS_CATALOG } from '../catalog/animations.catalog';
import { AVATAR_ITEMS_CATALOG } from '../catalog/avatar-items.catalog';
import { ITEMS_CATALOG } from '../catalog/items.catalog';
import { TEST_USERS_CATALOG } from '../catalog/test-users.catalog';
import WEARABLES from '../catalog/wearables.generated.json';
import type { WearableAsset } from '@chat-app/shared-types';
import { applySignupDefaults, grantDefaultAnimationsToAll } from './signup-defaults.service';
/**
 * Inserts any catalog entries that don't yet exist in the DB.
 * Existing documents are never modified — they are the stable source for
 * ObjectId references stored in user inventory.
 *
 * To apply catalog changes to existing records in development:
 *   drop the relevant collection and restart the server.
 */
export async function syncCatalog(): Promise<void> {
    await Promise.all([
        syncAnimations(),
        syncAvatarItems(),
        syncItems(),
    ]);
    // Test users run after items are seeded — applySignupDefaults depends on them
    await syncTestUsers();
    await grantDefaultAnimationsToAll();
}

async function syncAnimations(): Promise<void> {
    if (ANIMATIONS_CATALOG.length === 0) return;

    let inserted = 0;
    for (const entry of ANIMATIONS_CATALOG) {
        const result = await AnimationModel.findOneAndUpdate(
            { name: entry.name },
            { $setOnInsert: entry },
            { upsert: true, new: false },
        );
        if (result === null) inserted++;
    }

    console.log(`[catalog-sync] animations: ${inserted} inserted, ${ANIMATIONS_CATALOG.length - inserted} already exist`);
}

async function syncAvatarItems(): Promise<void> {
    if (AVATAR_ITEMS_CATALOG.length === 0) return;

    let inserted = 0;
    for (const entry of AVATAR_ITEMS_CATALOG) {
        const result = await AvatarItemModel.findOneAndUpdate(
            { name: entry.name },
            { $setOnInsert: entry },
            { upsert: true, new: false },
        );
        if (result === null) inserted++;
    }

    console.log(`[catalog-sync] avatar_items: ${inserted} inserted, ${AVATAR_ITEMS_CATALOG.length - inserted} already exist`);

    await syncNewVariants();
    await syncRigAssets();
}

/**
 * Appends catalog variants an existing item doesn't have yet (matched by name), such as a
 * new colour. Existing variants are left alone, so their _ids in inventories stay valid.
 * The name check and the push are one atomic update, so concurrent boots can't add a
 * variant twice.
 */
async function syncNewVariants(): Promise<void> {
    const existing = await AvatarItemModel.find({}, { name: 1, 'variants.name': 1 }).lean();
    const have = new Map(existing.map(i => [i.name, new Set(i.variants.map(v => v.name))]));
    let added = 0;
    for (const entry of AVATAR_ITEMS_CATALOG) {
        for (const { wearable: _wearable, ...variant } of entry.variants) {
            if (have.get(entry.name)?.has(variant.name)) continue;
            const result = await AvatarItemModel.updateOne(
                { name: entry.name, 'variants.name': { $ne: variant.name } },
                { $push: { variants: variant } },
            );
            added += result.modifiedCount;
        }
    }
    if (added > 0) console.log(`[catalog-sync] avatar_items: ${added} new variants added to existing items`);
}

/**
 * Attaches packed rig art to catalog variants. Unlike the rest of the catalog this
 * always overwrites: rigAsset is generated by scripts/pack-wearables.ts, so a re-pack
 * (new atlasVersion) must reach existing records. Variants are matched by name.
 */
async function syncRigAssets(): Promise<void> {
    const manifest = WEARABLES as unknown as Record<string, WearableAsset>;
    let attached = 0;
    for (const entry of AVATAR_ITEMS_CATALOG) {
        for (const variant of entry.variants) {
            if (!variant.wearable) continue;
            const rigAsset = manifest[variant.wearable];
            if (!rigAsset) {
                console.warn(`[catalog-sync] ${entry.name}/${variant.name}: no packed wearable "${variant.wearable}"; run art:pack`);
                continue;
            }
            await AvatarItemModel.updateOne(
                { name: entry.name },
                { $set: { 'variants.$[v].rigAsset': rigAsset } },
                { arrayFilters: [{ 'v.name': variant.name }] },
            );
            attached++;
        }
    }
    console.log(`[catalog-sync] avatar_items: rig art attached to ${attached} variants`);
}

async function syncItems(): Promise<void> {
    if (ITEMS_CATALOG.length === 0) return;

    let inserted = 0;
    for (const entry of ITEMS_CATALOG) {
        const result = await ItemModel.findOneAndUpdate(
            { name: entry.name },
            { $setOnInsert: entry },
            { upsert: true, new: false },
        );
        if (result === null) {
            inserted++;
            continue;
        }
        // Seats and front layers are tuned against the art, so existing records follow the catalog.
        const { seats, frontAssetUrl } = entry;
        const set = { ...(seats && { seats }), ...(frontAssetUrl && { frontAssetUrl }) };
        const unset = { ...(!seats && { seats: 1 }), ...(!frontAssetUrl && { frontAssetUrl: 1 }) };
        await ItemModel.updateOne({ name: entry.name }, {
            ...(Object.keys(set).length > 0 && { $set: set }),
            ...(Object.keys(unset).length > 0 && { $unset: unset }),
        });
    }

    console.log(`[catalog-sync] items: ${inserted} inserted, ${ITEMS_CATALOG.length - inserted} already exist`);
}

async function syncTestUsers(): Promise<void> {
    if (TEST_USERS_CATALOG.length === 0) return;

    let inserted = 0;
    for (const entry of TEST_USERS_CATALOG) {
        const exists = await UserModel.findOne({ username: entry.username }).select('_id').lean();
        if (exists) continue;

        try {
            const { password, ...rest } = entry;
            const hashed = await bcrypt.hash(password, 10);
            const user = new UserModel({ ...rest, password: hashed });
            const saved = await user.save();
            await applySignupDefaults(saved._id as any, saved.username);
            inserted++;
        } catch (e) {
            console.error(`[catalog-sync] Failed to seed test user "${entry.username}":`, e);
        }
    }

    console.log(`[catalog-sync] test_users: ${inserted} inserted, ${TEST_USERS_CATALOG.length - inserted} already exist`);
}
